"""Finite checks for a new, unreviewed analytic horizon sharpening.

Imports existing walkers read-only; writes only this directory's checks.json.
The finite checks are not a certificate at the astronomical K'.
"""
from collections import Counter
import json
from pathlib import Path
import random
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'work_global_ext' / 'route_c'))
from fdata import lam_walk, small_full, v2


def clock_factor(n):
    return 2 * (6*n*n + 4).bit_length()**2 + 1345


def shallow_bound(n, cutoff):
    return 3*n*clock_factor(n) + 4 < 1 << cutoff


def explicit_bound(cutoff):
    return (1 << cutoff) // (64*cutoff*cutoff)


def main():
    rng = random.Random(20261018)
    constants = 0
    endpoint_checks = 0
    # Consecutive exponents include both parities and every floor-log jump.
    exponents = list(range(64, 4097)) + [8192, 16384]
    for t in exponents:
        b = explicit_bound(t)
        assert 8*t*t + 24*t + 1363 <= 9*t*t
        assert 27*(1 << t) + 256 < 64*(1 << t)
        # Lemma MASS: 6+(54/64)2^T+48(1+9T^3) < 2^T, i.e. 64*(54+432T^3)+54*2^T < 64*2^T.
        assert 64*(54 + 432*t**3) + 54*(1 << t) < 64*(1 << t)
        # Squaring compares with the old cutoff even when t is odd.
        assert b*b > 1 << (t-4)
        assert b >= 1 << ((t+1)//2-1)
        assert b > t
        for n in (0, 1, b-1, b, rng.randrange(b+1)):
            assert clock_factor(n) <= 9*t*t
            assert shallow_bound(n, t)
            endpoint_checks += 1
        # A negative control: the criterion is not true at arbitrary indices.
        assert not shallow_bound(1 << t, t)
        constants += 1

    # A sharper inverse is illustrative only, not used in the theorem.
    examples = []
    for t in (64, 128, 256, 1024, 4096):
        lo, hi = 0, 1 << t
        while lo + 1 < hi:
            mid = (lo+hi)//2
            if shallow_bound(mid, t):
                lo = mid
            else:
                hi = mid
        assert shallow_bound(lo, t) and not shallow_bound(lo+1, t)
        assert lo >= explicit_bound(t)
        examples.append(dict(T=t, old_cutoff_log2=t//2-2,
                             explicit_cutoff_floor_log2=explicit_bound(t).bit_length()-1,
                             inverse_cutoff_floor_log2=lo.bit_length()-1))

    # Use the full pair walk to check the lambda-only walk and recover clocks
    # from the pair state's mass. No table generated by this script is assumed.
    count = 8192
    full = small_full(count)
    lam = lam_walk(count)
    kinds = Counter()
    source_checks = 0
    predicate_checks = 0
    fire = None
    for n in range(4, count):
        rec = full[n]
        tau = rec['tau']
        assert tau == lam['tau'][n]
        assert rec['typ'] == chr(lam['typ'][n])
        assert rec['odd'] == lam['odd'][n]
        assert tau <= n*clock_factor(n)
        kind = rec['typ']
        if kind == 'a':
            recovered_time = (rec['A'][1]-1)//3
        elif kind == 'b':
            recovered_time = (rec['A'][1]-1)//3
        else:
            recovered_time = (rec['A'][1]+rec['Y'][1]-1)//3
        assert recovered_time == tau
        if not rec['odd']:
            continue
        kinds[kind] += 1
        if kind == 'a':
            fire = (n, tau, v2(3*tau+4))
            continue
        assert fire is not None
        rho, fire_time, source_parameter = fire
        assert rho < n and fire_time <= tau
        assert (1 << source_parameter) <= 3*tau+4
        if kind == 'b':
            assert tau == fire_time and n == rho+1
            assert rec['omega'] == v2(3*tau+4) == source_parameter
        else:
            assert kind == 'c' and tau > fire_time
        source_checks += 1
        # Exercise successful and unsuccessful source-size filters at modest
        # cutoffs; this tests the implication only, not Theorem S at these T.
        for cutoff in range(1, 33):
            if shallow_bound(n, cutoff):
                assert source_parameter < cutoff
                if kind == 'b':
                    assert rec['omega'] < cutoff
                predicate_checks += 1
    assert kinds['a'] and kinds['b'] and kinds['c']

    for h in range(16, 4097):
        assert 3*(h-1)**2 + 4 < 1 << h
    result = dict(
        result='PASS', review_status='unreviewed',
        constant_exponents_checked=constants,
        clock_endpoint_checks=endpoint_checks,
        real_crossing_indices_checked=count-4,
        odd_crossing_counts=dict(kinds),
        bc_source_checks=source_checks,
        successful_source_predicate_checks=predicate_checks,
        horizon_transfer_inequality_checks=4097-16,
        examples=examples,
        scope='Finite checks supporting PROOF_CLOCK_HORIZON.md; no global theorem, no new level-5 certificate.'
    )
    Path(__file__).with_name('checks.json').write_text(
        json.dumps(result, indent=2)+'\n', encoding='utf-8')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
